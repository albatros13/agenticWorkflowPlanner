"""The eFLINT verifier agent handler (intent ``verify_eflint``).

A thin, in-process wrapper around the *external* eFLINT model-checking webservice
(``eflint-webservice`` from eflint-model-checking, default ``http://127.0.0.1:8100``). That
service speaks its own job API rather than this repo's agent contract, so the wrapper is an
:class:`AgentHandler` that acts as its HTTP client (:mod:`.client`).

What the wrapper adds on top of the raw service:

* PNML normalisation (profile + names; :mod:`.pnml`) so nets from ``petri_net_generator`` work;
* ``operation="auto"`` and a generated default compliance analysis when none is supplied;
* a single verdict (``passed`` / ``failed`` / ``inconclusive``) over the per-property outcomes,
  with the first counterexample/plan witness flattened for display;
* each verification is recorded under the agent's private storage ``runs/<run_id>/``
  (browse them with :meth:`EflintVerifierHandler.list_runs` / :meth:`EflintVerifierHandler.load_run`).

Service-level failures (unreachable, rejected request, compile/solver error, timeout) produce a
*failed* :class:`AgentResult`; a completed analysis that finds a counterexample is a *successful*
result whose ``output.verdict`` is ``failed``.
"""
from __future__ import annotations

import json
import logging
import os
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path

from pydantic import ValidationError

from agents.contract import AgentHandler, AgentManifest, AgentRequest, AgentResult, Capability
from agents.contract.models import JobStatus
from agents.storage import agent_storage

from .client import EflintVerifierClient, VerifierError
from .config import VerifierSettings
from .pnml import normalize_pnml, pn_transitions
from .schemas import ANALYSIS_OPERATIONS, PropertyResult, VerifyRequest, VerifyResponse

log = logging.getLogger(__name__)

AGENT_NAME = "eflint_verifier"
VERIFY_EFLINT = "verify_eflint"
_RUN_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")  # run folder names; blocks path traversal


def infer_operation(analysis: str | None) -> str:
    """Pick the analysis operation from the declarations present (properties win)."""
    text = _strip_comments(analysis or "")
    if re.search(r"(^|\.)\s*Property\b", text):
        return "model-check"
    if re.search(r"(^|\.)\s*Compliance-checking\b", text) or not text.strip():
        return "compliance-check"
    if re.search(r"(^|\.)\s*Plan\b", text):
        return "plan"
    return "model-check"


def default_compliance_analysis(transitions: list[str]) -> str:
    return ("// Generated by the eflint_verifier agent: no normative violation in any execution\n"
            "// of the process within the search bound.\n"
            f"Compliance-checking With Physical Actions = {', '.join(transitions)}.\n")


def verdict_of(operation: str, result: dict) -> str:
    if operation == "validate":
        return "passed" if result.get("valid") else "failed"
    if operation == "compile":
        return "passed"
    outcomes = [r.get("outcome") for r in result.get("results", [])] or [result.get("outcome")]
    if operation in ("model-check", "compliance-check"):
        if "counterexample" in outcomes:
            return "failed"
        return "passed" if all(o == "no_counterexample_within_bound" for o in outcomes) else "inconclusive"
    if operation == "plan":
        if outcomes and all(o == "plan_found" for o in outcomes):
            return "passed"
        return "failed" if "no_plan_within_bound" in outcomes else "inconclusive"
    return "passed" if all(o == "execution" for o in outcomes) else "inconclusive"  # run / explore


_OUTCOME_TEXT = {
    "no_counterexample_within_bound": "holds within bound {bound}",
    "counterexample": "VIOLATED — counterexample within bound {bound}",
    "plan_found": "plan found within bound {bound}",
    "no_plan_within_bound": "no plan within bound {bound}",
    "infeasible_configuration": "infeasible configuration (no execution possible)",
    "inconclusive": "inconclusive (solver did not complete)",
    "execution": "executed",
}


def describe(prop: PropertyResult) -> str:
    text = _OUTCOME_TEXT.get(prop.outcome, prop.outcome).format(bound=prop.bound)
    if prop.witness:
        text += ": " + " → ".join(", ".join(step) or "∅" for step in prop.witness)
    return f"'{prop.id}' {text}"


class EflintVerifierHandler(AgentHandler):
    def __init__(
        self,
        *,
        client: EflintVerifierClient | None = None,
        settings: VerifierSettings | None = None,
        runs_dir: Path | None = None,
    ):
        self._client = client
        self._settings = settings
        self._runs_dir = runs_dir

    def manifest(self) -> AgentManifest:
        return AgentManifest(
            name=AGENT_NAME,
            version="0.1.0",
            description=(
                "Verify a process model (Petri net, PNML or .pn) against an eFLINT normative "
                "specification through qualification rules, using the external eFLINT "
                "model-checking service: bounded property checking, compliance checking (no "
                "violations), planning, validation, execution and scenario exploration."
            ),
            supports_async=False,
            capabilities=[Capability(
                intent=VERIFY_EFLINT,
                description="Petri net + eFLINT + qualification rules (+ analysis) -> verdict with witnesses.",
                input_schema=VerifyRequest.model_json_schema(),
                output_schema=VerifyResponse.model_json_schema(),
            )],
        )

    # --- plumbing --------------------------------------------------------------------------
    def _settings_(self) -> VerifierSettings:
        return self._settings or VerifierSettings.from_env()

    def _client_(self) -> EflintVerifierClient:
        return self._client or EflintVerifierClient(self._settings_())

    def _runs(self) -> Path:
        if self._runs_dir is not None:
            return self._runs_dir
        if os.getenv("EFLINT_VERIFIER_RUNS_DIR"):
            return Path(os.environ["EFLINT_VERIFIER_RUNS_DIR"])
        return agent_storage(AGENT_NAME).path("runs")

    @staticmethod
    def _fail(intent: str, error: str, output: dict | None = None, run_id: str | None = None) -> AgentResult:
        return AgentResult(agent=AGENT_NAME, intent=intent, status=JobStatus.failed, error=error,
                           output=output or {}, artifacts_ref=run_id)

    # --- entry point -----------------------------------------------------------------------
    def handle(self, request: AgentRequest) -> AgentResult:
        if request.intent != VERIFY_EFLINT:
            return self._fail(request.intent, f"Unsupported intent {request.intent!r}; this agent serves {VERIFY_EFLINT!r}.")
        try:
            req = VerifyRequest.model_validate(request.payload)
        except ValidationError as exc:
            return self._fail(request.intent, "Invalid payload: " + "; ".join(
                f"{'.'.join(map(str, e['loc']))}: {e['msg']}" for e in exc.errors()[:5]))

        client = self._client_()
        service_url = client.settings.base_url
        run_id = uuid.uuid4().hex[:12]

        # 1. Physical model: normalise PNML, learn the transition names.
        physical = req.physical.model_dump()
        transitions, renamed, changes = [], {}, []
        if req.physical.language == "petri-net":
            if req.physical.format == "pnml":
                try:
                    names = normalize_pnml(req.physical.source)
                except ValueError as exc:
                    return self._fail(request.intent, str(exc))
                transitions = names.transitions
                if req.normalize_pnml:
                    physical["source"], renamed, changes = names.pnml, names.renamed, names.changes
            else:
                transitions = pn_transitions(req.physical.source)

        # 2. Operation + analysis (generate a compliance check when none was supplied).
        operation = req.operation
        analysis, generated = req.analysis, False
        if operation == "auto":
            operation = "explore" if req.scenario else infer_operation(analysis)
        target = req.target or (operation if operation in ANALYSIS_OPERATIONS else None)
        needs_analysis = operation in ANALYSIS_OPERATIONS or (
            operation in ("validate", "compile") and target in ANALYSIS_OPERATIONS)
        if needs_analysis and not (analysis or "").strip():
            if (target or operation) != "compliance-check" or not transitions:
                return self._fail(request.intent, f"An analysis document is required for {target or operation!r} "
                                                  "(no Petri net transitions to generate a compliance check from).")
            analysis, generated = default_compliance_analysis(transitions), True

        # 3. Build the service request.
        inputs: dict = {"physical": physical}
        if req.normative is not None:
            inputs["normative"] = req.normative.model_dump()
            inputs["qualification"] = req.qualification
        if needs_analysis:
            inputs["analysis"] = analysis
        if req.scenario and (operation == "explore" or target == "explore"):
            inputs["scenario"] = req.scenario
        options = req.options.model_dump(exclude_none=True)
        if needs_analysis and "max_states" not in options:
            options["max_states"] = client.settings.default_max_states
        if operation in ("validate", "compile"):
            options.pop("verbose", None)
        if not (operation == "plan" or target == "plan"):
            options.pop("all", None)
        body = {"operation": operation, "inputs": inputs, "options": options}
        if operation in ("validate", "compile") and target:
            body["target"] = target

        context = {"run_id": run_id, "operation": operation, "service_url": service_url,
                   "analysis": analysis if needs_analysis else None, "analysis_generated": generated,
                   "physical_transitions": transitions, "renamed": renamed, "pnml_changes": changes}

        # 4. Run the job.
        try:
            outcome = client.run(body)
        except VerifierError as exc:
            self._save(run_id, body, {**context, "error": {"code": exc.code, "message": str(exc)}})
            return self._fail(request.intent, f"{exc.code}: {exc}", output=context, run_id=run_id)
        except Exception:  # keep stack traces out of client responses
            log.exception("eFLINT verification failed (correlation_id=%s)", request.correlation_id)
            return self._fail(request.intent, "Internal error while calling the eFLINT verifier "
                                              f"(correlation_id={request.correlation_id}).")

        context.update(job_id=outcome.job_id, elapsed_s=outcome.elapsed_s)
        if outcome.status != "succeeded":
            err = outcome.error or {}
            message = f"{err.get('code', outcome.status)}: {err.get('message', 'the verification job ' + outcome.status)}"
            self._save(run_id, body, {**context, "status": outcome.status, "error": err})
            return self._fail(request.intent, message, output={**context, "job_status": outcome.status}, run_id=run_id)

        # 5. Interpret.
        result = outcome.result or {}
        props = [_property(r) for r in result.get("results", [])]
        if not props and "outcome" in result:  # explore
            props = [PropertyResult(id="scenario", outcome=result["outcome"])]
        verdict = verdict_of(operation, result)
        if operation == "validate":
            summary = "The inputs are valid." if verdict == "passed" else "The inputs are not valid."
        elif operation == "compile":
            summary = f"Compiled {len(result.get('programs', []))} ASP program(s)."
        else:
            summary = "; ".join(describe(p) for p in props) or "No results."
        response = VerifyResponse(**context, verdict=verdict, summary=summary, properties=props, raw_result=result)
        output = response.model_dump(mode="json")
        self._save(run_id, body, output)
        return AgentResult(agent=AGENT_NAME, intent=request.intent, status=JobStatus.succeeded,
                           output=output, artifacts_ref=run_id)

    def _save(self, run_id: str, body: dict, report: dict) -> None:
        try:
            run = self._runs() / run_id
            run.mkdir(parents=True, exist_ok=True)
            (run / "request.json").write_text(json.dumps(body, indent=2, ensure_ascii=False), encoding="utf-8")
            (run / "report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        except OSError:  # recording is best effort; never fail a verification over it
            log.warning("could not record eFLINT verification run %s", run_id, exc_info=True)


    # --- stored runs (browsing) -------------------------------------------------------------
    def list_runs(self) -> list[dict]:
        """Summaries of recorded verifications, newest first (unreadable folders are skipped)."""
        root = self._runs()
        if not root.is_dir():
            return []
        rows = []
        for run in root.iterdir():
            report_path = run / "report.json"
            if not (run.is_dir() and report_path.is_file()):
                continue
            try:
                report = json.loads(report_path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            error = report.get("error")
            rows.append({
                "run_id": run.name,
                "operation": report.get("operation", ""),
                "verdict": report.get("verdict") or ("error" if error else ""),
                "summary": report.get("summary") or (error or {}).get("message", ""),
                "error_code": (error or {}).get("code"),
                "properties": len(report.get("properties") or []),
                "elapsed_s": report.get("elapsed_s"),
                "created_at": datetime.fromtimestamp(report_path.stat().st_mtime, timezone.utc)
                .isoformat(timespec="seconds"),
            })
        rows.sort(key=lambda r: r["created_at"], reverse=True)
        return rows

    def load_run(self, run_id: str) -> dict:
        """``{run_id, report, request}`` of a recorded verification (``request`` may be ``{}``)."""
        if not _RUN_ID.match(run_id or ""):
            raise KeyError(f"invalid run id {run_id!r}")
        run = self._runs() / run_id
        if not (run / "report.json").is_file():
            raise KeyError(f"no recorded verification {run_id!r}")
        report = json.loads((run / "report.json").read_text(encoding="utf-8"))
        request_path = run / "request.json"
        request = json.loads(request_path.read_text(encoding="utf-8")) if request_path.is_file() else {}
        return {"run_id": run_id, "report": report, "request": request}


def _property(r: dict) -> PropertyResult:
    traces = r.get("traces") or []
    witness = []
    if traces and isinstance(traces[0], dict):
        witness = [list(s.get("actions", [])) for s in traces[0].get("steps", []) if isinstance(s, dict)]
    return PropertyResult(id=str(r.get("id", "?")), outcome=str(r.get("outcome", "?")), bound=r.get("bound"),
                          witness=witness, completion=r.get("completion"))


def _strip_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", text)


